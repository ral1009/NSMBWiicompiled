"""Generate everything a non-PAL game version's build needs from the PAL-written tree.

Usage:
  python projects/nsmbw/tools/gen_version_tables.py E1

Reads NSMBW-Maps/address-map.txt, the sources, projects/nsmbw/*.yml and modules.txt, and the
version's code in NSMBW-Versions/<V>/ (unpack_game_code.py) plus its function_map.txt
(map_function_map.py). Writes generated_nsmbw-<V>/:
  version/nsmbw_va_ranges.inc   {P1 start, P1 end, offset} rows for NSMBW_VA (runtime/include/nsmbw_va.h)
  version/nsmbw_va_tokens.h     #define NSMBW_VA_TOK_<P1 hex> <V hex> for every hook / NSMBW_FUNC token
                                in runtime/ and projects/nsmbw/native/, plus the r13/r2 bases
  native_scan/                  projects/nsmbw/native/ with every routed address already converted,
                                for the translator, which finds our overrides by reading these sources
                                (its regexes see `PPC_NATIVE_OVERRIDE(<hex>, ...)`, not macros)
  projects/*.yml, modules.txt   the translator projects for <V>: its code, function map, r13/r2,
                                REL load addresses, native_scan/ and build/nsmbw-<V>* outputs

A hook token the map cannot convert stays as it is when it is in the shared runtime (Mario Kart Wii
addresses that are dead code for NSMBW, see CLAUDE.md); in projects/nsmbw/native it is an error.
"""
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from nsmbw_address_map import AddressMap  # noqa: E402
import map_function_map  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
NATIVE = ROOT / "projects" / "nsmbw" / "native"
HOOK_TOKEN = re.compile(r"\b(?:PPC_NATIVE_OVERRIDE(?:_VOID)?|GX_FATAL_STUB)\s*\(\s*([0-9A-Fa-f]{8})\b")
FUNC_TOKEN = re.compile(r"\bNSMBW_(?:FUNC|TOKEN)\(\s*([0-9A-Fa-f]{8})\s*\)")


def fmt(value, like):
    return ("%08x" if any(c in "abcdef" for c in like) else "%08X") % value


def source_files():
    for base in (ROOT / "runtime" / "src", ROOT / "runtime" / "include", NATIVE):
        for f in base.rglob("*"):
            if f.suffix in (".cpp", ".h", ".inc", ".hpp"):
                yield f


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    v = sys.argv[1]
    amap = AddressMap.load()
    if amap.parents.get(v) != "P1":
        sys.exit("%s does not extend P1 directly; only that case is supported" % v)
    out = ROOT / ("generated_nsmbw-" + v)
    (out / "version").mkdir(parents=True, exist_ok=True)
    code = ROOT / "NSMBW-Versions" / v
    fmap = code / "function_map.txt"
    if not fmap.exists():
        sys.exit("run map_function_map.py first (%s missing)" % fmap)

    # -- ranges
    rows = ["    {0x%08Xu, 0x%08Xu, %d}," % (s, e, o) for s, e, o in amap.ranges[v]]
    (out / "version" / "nsmbw_va_ranges.inc").write_text(
        "// Generated by gen_version_tables.py from NSMBW-Maps/address-map.txt [%s]. Do not edit.\n" % v
        + "\n".join(rows) + "\n")

    # -- tokens
    tokens, errors, kept = {}, [], []
    for f in source_files():
        text = f.read_text(encoding="utf-8", errors="replace")
        in_native = NATIVE in f.parents
        for pattern, strict in ((HOOK_TOKEN, in_native), (FUNC_TOKEN, True)):
            for m in pattern.finditer(text):
                t = m.group(1)
                if int(t, 16) < 0x80000000:  # low-memory stubs (0x00000060) are not game memory
                    tokens[t] = t
                    continue
                mapped = amap.convert(int(t, 16), "P1", v)
                if mapped is None:
                    if strict:
                        errors.append("%s: %s has no %s counterpart" % (f.relative_to(ROOT), t, v))
                        continue
                    mapped = int(t, 16)
                    kept.append(t)
                tokens[t] = fmt(mapped, t)
    if errors:
        sys.exit("\n".join(sorted(set(errors))))
    sda13p, sda2p = map_function_map.SDA["P1"]
    sda13, sda2 = map_function_map.SDA[v]
    lines = ["// Generated by gen_version_tables.py for %s. Do not edit." % v, "#pragma once",
             "#define NSMBW_VA_SDA13_P1 0x%08Xu" % sda13p, "#define NSMBW_VA_SDA2_P1 0x%08Xu" % sda2p,
             "#define NSMBW_VA_SDA13 0x%08Xu" % sda13, "#define NSMBW_VA_SDA2 0x%08Xu" % sda2]
    lines += ["#define NSMBW_VA_TOK_%s %s" % (t, tokens[t]) for t in sorted(tokens)]
    (out / "version" / "nsmbw_va_tokens.h").write_text("\n".join(lines) + "\n")

    # -- the translator's copy of projects/nsmbw/native
    scan = out / "native_scan"
    if scan.exists():
        shutil.rmtree(scan)
    scan.mkdir(parents=True)

    def conv(addr, strict=True):
        m = amap.convert(addr, "P1", v)
        if m is None and strict:
            raise SystemExit("unmapped address 0x%08X in native sources" % addr)
        return addr if m is None else m

    for f in sorted(NATIVE.iterdir()):
        if not f.is_file():
            continue
        t = f.read_text(encoding="utf-8", errors="replace")
        t = re.sub(r"NSMBW_VA_PAIR\(\s*0[xX]([0-9A-Fa-f]{8})[uU]?\s*,\s*(-?\d+)\s*\)",
                   lambda m: "0x%08Xu" % ((conv((int(m.group(1), 16) + int(m.group(2))) & 0xFFFFFFFF) - int(m.group(2))) & 0xFFFFFFFF), t)
        t = re.sub(r"NSMBW_VA\(\s*0[xX]([0-9A-Fa-f]{8})[uU]?\s*\)", lambda m: "0x%08Xu" % conv(int(m.group(1), 16)), t)
        t = FUNC_TOKEN.sub(lambda m: "func_" + tokens[m.group(1)], t)
        t = HOOK_TOKEN.sub(lambda m: m.group(0)[:m.start(1) - m.start(0)] + tokens[m.group(1)], t)
        t = re.sub(r"\b(REGISTER_NATIVE_FUNCTION(?:_AS)?|REGISTER_TRANSLATED_FUNCTION|MKW_KNOWN_TYPED_NATIVE|MKW_KNOWN_NATIVE_CPU_CALL)\s*\(\s*0[xX]([0-9A-Fa-f]{8})",
                   lambda m: "%s(0x%08X" % (m.group(1), conv(int(m.group(2), 16), strict=False)), t)
        (scan / f.name).write_text(t, encoding="utf-8")

    # -- translator projects and the modules file
    rel_load = {n: conv(a) for n, a in map_function_map.REL_LOAD_P1.items()}
    (out / "projects").mkdir(exist_ok=True)
    for src in sorted((ROOT / "projects" / "nsmbw").glob("nsmbw*.yml")):
        t = src.read_text(encoding="utf-8")
        rel = re.search(r"(d_\w+NP)", src.name)
        t = t.replace("workspace_root: ../..", "workspace_root: ../..")  # generated_nsmbw-V/projects -> root
        t = re.sub(r"id: nsmbw", "id: nsmbw-%s" % v, t, count=1)
        t = re.sub(r"sda_base: 0x[0-9A-Fa-f]+", "sda_base: 0x%08X" % sda13, t)
        t = re.sub(r"sda2_base: 0x[0-9A-Fa-f]+", "sda2_base: 0x%08X" % sda2, t)
        t = t.replace("NSMBW-Decomp/original/wiimj2d.dol", "NSMBW-Versions/%s/main.dol" % v)
        t = re.sub(r"NSMBW-Decomp/original/(d_\w+NP)\.rel", r"NSMBW-Versions/%s/\1.rel" % v, t)
        if rel:
            t = re.sub(r"load_address: 0x[0-9A-Fa-f]+", "load_address: 0x%08X" % rel_load[rel.group(1)], t)
        t = t.replace("path: projects/nsmbw/function_map.txt", "path: NSMBW-Versions/%s/function_map.txt" % v)
        t = t.replace("native_registration_root: projects/nsmbw/native", "native_registration_root: generated_nsmbw-%s/native_scan" % v)
        t = t.replace("native_abi_directories: [projects/nsmbw/native]", "native_abi_directories: [generated_nsmbw-%s/native_scan]" % v)
        t = re.sub(r"root: build/nsmbw", "root: build/nsmbw-%s" % v, t)
        (out / "projects" / src.name).write_text(t, encoding="utf-8")
    mods = []
    for line in (ROOT / "projects" / "nsmbw" / "modules.txt").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            mods.append(line)
            continue
        parts = line.split()
        parts[1] = parts[1].replace("/build/nsmbw", "/build/nsmbw-%s" % v)
        parts[2] = parts[2].replace("/build/nsmbw", "/build/nsmbw-%s" % v)
        for i in (3, 4):
            if len(parts) > i:
                parts[i] = "0x%08X" % conv(int(parts[i], 16))
        mods.append(" ".join(parts))
    # modules.txt paths are relative to its own folder (projects/nsmbw); generated_nsmbw-V/ is one
    # level up from projects/, so ../../build stays right only from a two-deep folder: use projects/.
    (out / "projects" / "modules.txt").write_text("\n".join(mods) + "\n")

    print("%s: %d ranges, %d tokens (%d shared-runtime tokens unmapped, kept as they are), native_scan %d files"
          % (v, len(rows), len(tokens), len(set(kept)), len(list(scan.iterdir()))))
    print("REL load addresses: " + ", ".join("%s 0x%08X" % kv for kv in rel_load.items()))


if __name__ == "__main__":
    main()
